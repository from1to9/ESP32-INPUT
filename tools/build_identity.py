#!/usr/bin/env python3
"""Generate bounded firmware identity from project metadata and the actual checkout."""
import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile


def git(root, *args):
    return subprocess.check_output(
        ["git", "-C", str(root), *args], text=True, stderr=subprocess.DEVNULL,
        timeout=10).strip()


def checkout_identity(root):
    """An archive inside another repository must not inherit its identity."""
    commit = ""
    try:
        if Path(git(root, "rev-parse", "--show-toplevel")).resolve() != root.resolve():
            return commit, "unknown"
        candidate = git(root, "rev-parse", "HEAD")
        if not re.fullmatch(r"[0-9a-f]{40}", candidate):
            return commit, "unknown"
        commit = candidate
        changes = git(root, "status", "--porcelain=v1", "--untracked-files=all",
                      "--ignore-submodules=none")
        return commit, "dirty" if changes else "clean"
    except (OSError, subprocess.SubprocessError):
        return commit, "unknown"


def project_identity(root):
    data = json.loads((root / "firmware/project_identity.json").read_text(encoding="utf-8"))
    if set(data) != {"schema_version", "developer", "repository_url"} or type(data["schema_version"]) is not int or data["schema_version"] != 1:
        raise ValueError("Unsupported project identity schema")
    for name, capacity in (("developer", 32), ("repository_url", 96)):
        value = data[name]
        if not isinstance(value, str) or not value or value != value.strip() or len(value.encode("utf-8")) >= capacity or any(not 32 <= ord(char) <= 126 for char in value):
            raise ValueError(f"Invalid or oversized {name}")
    # The device validates this same bounded DNS repository URL grammar. This
    # deliberately supports a documented subset of URLs, not arbitrary URIs.
    url = re.fullmatch(r"https://([^/:]+)(?::([0-9]{1,5}))?/(.+)", data["repository_url"])
    if url is None:
        raise ValueError("Repository URL must use HTTPS, a DNS host and a nonempty path")
    host, port, path = url.groups()
    labels = host.split(".")
    label = r"[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?"
    if len(labels) < 2 or any(re.fullmatch(label, part) is None for part in labels):
        raise ValueError("Repository URL has an unsupported DNS host")
    if port is not None and not 1 <= int(port) <= 65535:
        raise ValueError("Repository URL port must be 1..65535")
    if re.fullmatch(r"(?:[A-Za-z0-9/._~!$&'()*+,;=:@-]|%[A-Fa-f0-9]{2})+", path) is None:
        raise ValueError("Repository URL path must use URL characters or valid percent escapes")
    commit, state = checkout_identity(root)
    return {"developer": data["developer"], "repository_url": data["repository_url"],
            "git_commit": commit, "git_state": state}


def write_changed(path, text):
    """Preserve no-op timestamps; publish complete metadata with one replacement."""
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", newline="\n",
                                         dir=path.parent, delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(text)
        os.replace(temporary, path)
    finally:
        if temporary and temporary.exists():
            temporary.unlink()


def generate(root, output):
    data = project_identity(root)
    lines = ["// Generated by tools/build_identity.py; do not edit.", "#pragma once"]
    for name in ("developer", "repository_url", "git_commit", "git_state"):
        lines.append(f"#define APP_BUILD_{name.upper()} {json.dumps(data[name], ensure_ascii=True)}")
    lines.append(f"#define APP_BUILD_GIT_KNOWN {int(bool(data['git_commit']))}")
    lines.append(f"#define APP_BUILD_GIT_DIRTY {int(data['git_state'] == 'dirty')}")
    lines.append(f"#define APP_BUILD_GIT_STATE_KNOWN {int(data['git_state'] != 'unknown')}")
    write_changed(output, "\n".join(lines) + "\n")
    return data


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    try:
        generate(args.root.resolve(), args.output.resolve())
    except (OSError, ValueError) as error:
        parser.exit(1, f"Build identity error: {error}\n")


if __name__ == "__main__":
    main()
