#pragma once

/* UAC2 entities have local IDs; interface IDs follow the existing CDC/HID.
 * Both speeds use a 1 ms service interval (FS=1, HS=4), 48 kHz mono PCM16.
 * Playback uses explicit asynchronous feedback; capture uses TinyUSB's IN
 * flow control. No descriptor advertises stereo, a host identity or local
 * microphone consent. Selecting an alternate interface never opens the codec. */
#define INPUT_USB_AUDIO_CONTROL_INTERFACE 3
#define INPUT_USB_AUDIO_PLAYBACK_INTERFACE 4
#define INPUT_USB_AUDIO_CAPTURE_INTERFACE 5
#define INPUT_USB_AUDIO_CLOCK_ID 4
#define INPUT_USB_AUDIO_RATE 48000U
#define INPUT_USB_AUDIO_PACKET_BYTES 98U
#define INPUT_USB_AUDIO_DESC_LENGTH (TUD_AUDIO20_DESC_IAD_LEN + \
    TUD_AUDIO20_DESC_STD_AC_LEN + TUD_AUDIO20_DESC_CS_AC_LEN + \
    TUD_AUDIO20_DESC_CLK_SRC_LEN + 2 * TUD_AUDIO20_DESC_INPUT_TERM_LEN + \
    2 * TUD_AUDIO20_DESC_OUTPUT_TERM_LEN + 4 * TUD_AUDIO20_DESC_STD_AS_LEN + \
    2 * TUD_AUDIO20_DESC_CS_AS_INT_LEN + 2 * TUD_AUDIO20_DESC_TYPE_I_FORMAT_LEN + \
    3 * TUD_AUDIO20_DESC_STD_AS_ISO_EP_LEN + 2 * TUD_AUDIO20_DESC_CS_AS_ISO_EP_LEN)

#define INPUT_USB_AUDIO_DESCRIPTOR(interval) \
    TUD_AUDIO20_DESC_IAD(INPUT_USB_AUDIO_CONTROL_INTERFACE, 3, 0), \
    TUD_AUDIO20_DESC_STD_AC(INPUT_USB_AUDIO_CONTROL_INTERFACE, 0, 0), \
    TUD_AUDIO20_DESC_CS_AC(0x0200, AUDIO20_FUNC_HEADSET, \
        TUD_AUDIO20_DESC_CLK_SRC_LEN + 2 * TUD_AUDIO20_DESC_INPUT_TERM_LEN + \
        2 * TUD_AUDIO20_DESC_OUTPUT_TERM_LEN, AUDIO20_CTRL_NONE), \
    TUD_AUDIO20_DESC_CLK_SRC(INPUT_USB_AUDIO_CLOCK_ID, 1, 5, 0, 0), \
    TUD_AUDIO20_DESC_INPUT_TERM(1, AUDIO_TERM_TYPE_USB_STREAMING, 0x13, \
        INPUT_USB_AUDIO_CLOCK_ID, 1, AUDIO20_CHANNEL_CONFIG_NON_PREDEFINED, 0, 0, 0), \
    TUD_AUDIO20_DESC_OUTPUT_TERM(3, AUDIO_TERM_TYPE_OUT_DESKTOP_SPEAKER, 0, 1, \
        INPUT_USB_AUDIO_CLOCK_ID, 0, 0), \
    TUD_AUDIO20_DESC_INPUT_TERM(0x11, AUDIO_TERM_TYPE_IN_GENERIC_MIC, 0, \
        INPUT_USB_AUDIO_CLOCK_ID, 1, AUDIO20_CHANNEL_CONFIG_NON_PREDEFINED, 0, 0, 0), \
    TUD_AUDIO20_DESC_OUTPUT_TERM(0x13, AUDIO_TERM_TYPE_USB_STREAMING, 1, 0x11, \
        INPUT_USB_AUDIO_CLOCK_ID, 0, 0), \
    TUD_AUDIO20_DESC_STD_AS_INT(INPUT_USB_AUDIO_PLAYBACK_INTERFACE, 0, 0, 0), \
    TUD_AUDIO20_DESC_STD_AS_INT(INPUT_USB_AUDIO_PLAYBACK_INTERFACE, 1, 2, 0), \
    TUD_AUDIO20_DESC_CS_AS_INT(1, AUDIO20_CTRL_NONE, AUDIO20_FORMAT_TYPE_I, \
        AUDIO20_DATA_FORMAT_TYPE_I_PCM, 1, AUDIO20_CHANNEL_CONFIG_NON_PREDEFINED, 0), \
    TUD_AUDIO20_DESC_TYPE_I_FORMAT(2, 16), \
    TUD_AUDIO20_DESC_STD_AS_ISO_EP(0x04, \
        TUSB_XFER_ISOCHRONOUS | TUSB_ISO_EP_ATT_ASYNCHRONOUS | TUSB_ISO_EP_ATT_DATA, \
        INPUT_USB_AUDIO_PACKET_BYTES, interval), \
    TUD_AUDIO20_DESC_CS_AS_ISO_EP(AUDIO20_CS_AS_ISO_DATA_EP_ATT_NON_MAX_PACKETS_OK, \
        AUDIO20_CTRL_NONE, AUDIO20_CS_AS_ISO_DATA_EP_LOCK_DELAY_UNIT_UNDEFINED, 0), \
    TUD_AUDIO20_DESC_STD_AS_ISO_EP(0x85, \
        TUSB_XFER_ISOCHRONOUS | TUSB_ISO_EP_ATT_NO_SYNC | TUSB_ISO_EP_ATT_EXPLICIT_FB, \
        4, interval), \
    TUD_AUDIO20_DESC_STD_AS_INT(INPUT_USB_AUDIO_CAPTURE_INTERFACE, 0, 0, 0), \
    TUD_AUDIO20_DESC_STD_AS_INT(INPUT_USB_AUDIO_CAPTURE_INTERFACE, 1, 1, 0), \
    TUD_AUDIO20_DESC_CS_AS_INT(0x13, AUDIO20_CTRL_NONE, AUDIO20_FORMAT_TYPE_I, \
        AUDIO20_DATA_FORMAT_TYPE_I_PCM, 1, AUDIO20_CHANNEL_CONFIG_NON_PREDEFINED, 0), \
    TUD_AUDIO20_DESC_TYPE_I_FORMAT(2, 16), \
    TUD_AUDIO20_DESC_STD_AS_ISO_EP(0x84, \
        TUSB_XFER_ISOCHRONOUS | TUSB_ISO_EP_ATT_ASYNCHRONOUS | TUSB_ISO_EP_ATT_DATA, \
        INPUT_USB_AUDIO_PACKET_BYTES, interval), \
    TUD_AUDIO20_DESC_CS_AS_ISO_EP(AUDIO20_CS_AS_ISO_DATA_EP_ATT_NON_MAX_PACKETS_OK, \
        AUDIO20_CTRL_NONE, AUDIO20_CS_AS_ISO_DATA_EP_LOCK_DELAY_UNIT_UNDEFINED, 0)
